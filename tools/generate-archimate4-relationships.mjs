import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const input = path.join(root, 'resources', 'archimate4', 'relationships', 'archimate4_relationships_normalized.csv');
const output = path.join(root, 'lib', 'archimate4', 'generated', 'RelationshipMatrix.generated.js');

function parseCsv(text) {
  const rows = [];
  let row = [], value = '', quoted = false;
  for (let index = 0; index < text.length; index++) {
    const character = text[index];
    if (character === '"') {
      if (quoted && text[index + 1] === '"') { value += '"'; index++; }
      else quoted = !quoted;
    } else if (character === ',' && !quoted) { row.push(value); value = ''; }
    else if ((character === '\n' || character === '\r') && !quoted) {
      if (character === '\r' && text[index + 1] === '\n') index++;
      row.push(value); value = '';
      if (row.some(Boolean)) rows.push(row);
      row = [];
    } else value += character;
  }
  if (value || row.length) { row.push(value); rows.push(row); }
  return rows;
}

const [ headers, ...values ] = parseCsv(fs.readFileSync(input, 'utf8').replace(/^\uFEFF/, ''));
const required = [ 'source_domain', 'source', 'target_domain', 'target', 'relationship', 'code' ];
for (const name of required) if (!headers.includes(name)) throw new Error(`Missing CSV column: ${name}`);
const column = Object.fromEntries(headers.map((name, index) => [ name, index ]));
const matrix = {}, concepts = new Map(), codes = {};
const triples = new Set();

for (const row of values) {
  const source = row[column.source], target = row[column.target];
  const relationship = row[column.relationship], code = row[column.code];
  concepts.set(source, row[column.source_domain]);
  concepts.set(target, row[column.target_domain]);
  codes[relationship] = code;
  const triple = `${source}\u0000${relationship}\u0000${target}`;
  if (triples.has(triple)) throw new Error(`Duplicate relationship triple: ${source} / ${relationship} / ${target}`);
  triples.add(triple);
  matrix[source] ||= {};
  matrix[source][target] ||= [];
  matrix[source][target].push(relationship);
}

if (concepts.size !== 42) throw new Error(`Expected 42 concepts, found ${concepts.size}`);
if (Object.keys(codes).length !== 11) throw new Error(`Expected 11 relationships, found ${Object.keys(codes).length}`);
for (const targets of Object.values(matrix)) {
  for (const relationships of Object.values(targets)) relationships.sort();
}

const generated = `// Generated by tools/generate-archimate4-relationships.mjs. Do not edit.\n` +
  `export const RELATIONSHIP_MATRIX_DATA = Object.freeze(${JSON.stringify(matrix, null, 2)});\n\n` +
  `export const RELATIONSHIP_MATRIX_METADATA = Object.freeze(${JSON.stringify({
    source: 'archimate4_relationships_normalized.csv',
    conceptCount: concepts.size,
    relationshipCount: Object.keys(codes).length,
    tripleCount: triples.size,
    concepts: [ ...concepts ].map(([ name, domain ]) => ({ name, domain })),
    codes
  }, null, 2)});\n`;

fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, generated);
console.log(`Generated ${triples.size} ArchiMate relationship triples at ${path.relative(root, output)}`);
